"""Export QA test cases to pytest and Cypress files."""

from __future__ import annotations

import re
from pathlib import Path

from shared.qa.models import QaResult, TestCaseItem

_SLUG_RE = re.compile(r"[^a-z0-9]+")


def _slug(text: str, *, max_len: int = 40) -> str:
    slug = _SLUG_RE.sub("_", (text or "test").lower()).strip("_")
    return (slug or "test")[:max_len]


def _safe_id(test_id: str) -> str:
    return re.sub(r"[^a-zA-Z0-9_]", "_", test_id.replace("-", "_"))


def export_pytest_module(
    qa: QaResult,
    *,
    task_key: str | None = None,
    branch_name: str = "",
) -> tuple[str, str]:
    """Return (relative_path, file_content) for a pytest module."""
    key = (task_key or "QA").upper()
    slug = _slug(branch_name.split("/")[-1] if branch_name else key)
    rel_path = f"tests/generated/test_{key.lower()}_{slug}.py"
    lines: list[str] = [
        '"""Auto-generated by QA Agent — review before merging."""',
        "",
        "import pytest",
        "",
        f'BRANCH = "{branch_name}"',
        f'TASK_KEY = "{key}"',
        "",
        f"class Test{key.replace('-', '')}{slug.title().replace('_', '')}:",
        f'    """QA tests for {key} ({branch_name})."""',
        "",
    ]
    if not qa.test_cases:
        lines.extend([
            "    @pytest.mark.skip(reason='No test cases generated by QA Agent')",
            "    def test_placeholder(self):",
            "        pytest.fail('Fill in QA test cases')",
            "",
        ])
    else:
        for tc in qa.test_cases:
            lines.extend(_pytest_test_method(tc))
    return rel_path, "\n".join(lines)


def _pytest_test_method(tc: TestCaseItem) -> list[str]:
    fn = f"test_{_safe_id(tc.id).lower()}"
    lines = [
        "",
        f"    def {fn}(self):",
        f'        """{tc.title} [{tc.priority}]"""',
    ]
    if tc.preconditions:
        lines.append(f"        # Preconditions: {tc.preconditions}")
    for idx, step in enumerate(tc.steps or [], start=1):
        lines.append(f"        # Step {idx}: {step}")
    if not tc.steps:
        lines.append("        # TODO: implement steps from QA Agent output")
    expected = tc.expected_result or "expected outcome"
    lines.append(f"        assert True  # Expected: {expected}")
    return lines


def export_cypress_spec(
    qa: QaResult,
    *,
    task_key: str | None = None,
    branch_name: str = "",
) -> tuple[str, str]:
    """Return (relative_path, file_content) for a Cypress spec."""
    key = (task_key or "QA").upper()
    slug = _slug(branch_name.split("/")[-1] if branch_name else key)
    rel_path = f"cypress/e2e/{key.lower()}_{slug}.cy.ts"
    lines: list[str] = [
        "/** Auto-generated by QA Agent — review before merging. */",
        "",
        f"describe('{key} — {branch_name}', () => {{",
        f"  const taskKey = '{key}';",
        "",
    ]
    if not qa.test_cases:
        lines.extend([
            "  it.skip('placeholder — no test cases from QA Agent', () => {",
            "    cy.log('Fill in QA test cases');",
            "  });",
            "",
        ])
    else:
        for tc in qa.test_cases:
            title = tc.title.replace("'", "\\'")
            lines.append(f"  it('{tc.id}: {title}', () => {{")
            if tc.preconditions:
                lines.append(f"    // Preconditions: {tc.preconditions}")
            for step in tc.steps or []:
                lines.append(f"    // {step}")
            if not tc.steps:
                lines.append("    cy.visit('/'); // TODO: adjust URL")
            lines.append(f"    // Expected: {tc.expected_result or 'success'}")
            lines.append("  });")
            lines.append("")
    lines.append("});")
    lines.append("")
    return rel_path, "\n".join(lines)


def export_test_cases_markdown(
    qa: QaResult,
    *,
    task_key: str | None = None,
    branch_name: str = "",
    run_id: str = "",
) -> str:
    """Markdown report for Jira attachment."""
    key = task_key or "N/A"
    parts = [
        f"# QA Test Cases — {key}",
        "",
        f"- **Branch:** `{branch_name}`",
        f"- **Verdict:** {qa.verdict}",
        f"- **Run ID:** `{run_id}`",
        "",
        "## Summary",
        qa.summary or "(no summary)",
        "",
    ]
    if qa.test_cases:
        parts.append("## Test Cases")
        parts.append("")
        parts.append("| ID | Title | Priority | Expected |")
        parts.append("|----|-------|----------|----------|")
        for tc in qa.test_cases:
            expected = (tc.expected_result or "").replace("|", "/")
            parts.append(f"| {tc.id} | {tc.title} | {tc.priority} | {expected} |")
        parts.append("")
    if qa.gaps:
        parts.append("## Gaps")
        for gap in qa.gaps:
            parts.append(f"- {gap}")
        parts.append("")
    return "\n".join(parts)


def write_export_files(
    base_dir: Path,
    run_id: str,
    files: dict[str, str],
) -> list[dict[str, str]]:
    """Write export files to disk; return list of {path, size}."""
    out_dir = base_dir / run_id
    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[dict[str, str]] = []
    for rel_path, content in files.items():
        target = out_dir / rel_path.replace("/", Path.sep)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        written.append({"path": str(target), "relative": rel_path, "size": str(len(content))})
    return written
